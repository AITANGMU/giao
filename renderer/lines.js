// 当前激活的语音（按装扮切换）
window.LINES = window.VOICES.default;

// 台词选择与去重复
window.Lines = {
  recent: {},

  // 从一个池子里取一条并渲染占位符
  pick(key, vars) {
    const pool = (window.LINES && window.LINES[key]) || [];
    const item = this.pickArr(pool, key);
    return this.render(item, vars);
  },

  // 从任意数组取一条（避开上一条），支持函数项
  pickArr(arr, key) {
    if (!arr || !arr.length) return '';
    let idx = 0;
    if (arr.length > 1) {
      const last = this.recent[key];
      do { idx = Math.floor(Math.random() * arr.length); } while (idx === last);
    }
    this.recent[key] = idx;
    const item = arr[idx];
    return typeof item === 'function' ? item() : item;
  },

  // 替换 {name} {text} {todo_count} {h} 等占位符
  render(s, vars) {
    if (!s) return '';
    return s.replace(/\{(\w+)\}/g, (m, k) => (vars && vars[k] !== undefined ? vars[k] : ''));
  },

  // 关键词对话回复；vars 用于替换 {name} 等占位符
  chatReply(text, vars) {
    const t = String(text || '').toLowerCase();
    const kb = window.LINES.chat_kb || [];
    for (let gi = 0; gi < kb.length; gi++) {
      const g = kb[gi];
      if (g.k.some((kw) => t.includes(kw))) {
        return this.render(this.pickArr(g.r, 'chat_' + gi), vars);
      }
    }
    return this.render(this.pickArr(window.LINES.chat_default, 'chat_default'), vars);
  }
};
